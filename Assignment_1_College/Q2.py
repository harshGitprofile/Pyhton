a = int(input("Enter the value of a : "))
b = int(input("Enter the value of b : "))
print(f"Sum of {a} and {b} is {a+b}\nDifference of {a} and {b} is {a-b}\nProduct of {a} and {b} is {a*b}")
print(f"Division of {a} and {b} is {a/b}\nFloor Division of {a} and {b} is {a//b}\n")
print(f"Remainder of {a} and {b} is {a%b}")

